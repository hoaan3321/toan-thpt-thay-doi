-- Lưu ý: service_role bỏ qua RLS và chỉ dùng ở máy chủ/script import nội bộ.
-- Không đưa SUPABASE_SERVICE_ROLE_KEY vào mã frontend hoặc repo công khai.

-- Bảng tối thiểu cho luồng đề/lớp/giao bài. Bản đầu của frontend tập trung ngân hàng,
-- lý thuyết, tạo mã đề và in đề; luồng học sinh nộp bài/chấm tự động cần bổ sung API/UI riêng.

create table if not exists public.exams (
  id bigint generated by default as identity primary key,
  title text not null,
  grade smallint not null check (grade in (10, 11, 12)),
  scope_chapter text not null default '',
  scope_lesson text not null default '',
  matrix jsonb not null default '{}'::jsonb,
  codes jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.classes (
  id bigint generated by default as identity primary key,
  name text not null,
  grade smallint not null check (grade in (10, 11, 12)),
  created_at timestamptz not null default now()
);

create table if not exists public.students (
  id bigint generated by default as identity primary key,
  class_id bigint not null references public.classes(id) on delete cascade,
  full_name text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.assignments (
  id bigint generated by default as identity primary key,
  exam_id bigint not null references public.exams(id) on delete cascade,
  class_id bigint references public.classes(id) on delete set null,
  join_code text not null unique,
  is_open boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  assignment_id bigint not null references public.assignments(id) on delete cascade,
  student_id bigint references public.students(id) on delete set null,
  student_name text not null default '',
  code_index integer not null default 0,
  answers jsonb not null default '{}'::jsonb,
  score numeric(6, 2),
  detail jsonb not null default '{}'::jsonb,
  submitted_at timestamptz not null default now()
);

create index if not exists students_class_idx on public.students (class_id);
create index if not exists assignments_exam_idx on public.assignments (exam_id);
create index if not exists submissions_assignment_idx on public.submissions (assignment_id);

alter table public.exams enable row level security;
alter table public.classes enable row level security;
alter table public.students enable row level security;
alter table public.assignments enable row level security;
alter table public.submissions enable row level security;

grant select, insert, update, delete on public.exams, public.classes, public.students, public.assignments, public.submissions to authenticated;
grant all on public.exams, public.classes, public.students, public.assignments, public.submissions to service_role;
grant usage, select on all sequences in schema public to authenticated, service_role;

