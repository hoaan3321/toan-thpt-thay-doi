create table if not exists public.questions (
  id bigint primary key,
  grade smallint not null check (grade in (10, 11, 12)),
  chapter text not null,
  dang text not null,
  level text not null check (level in ('NB', 'TH', 'VD', 'VDC')),
  qtype text not null check (qtype in ('single', 'tf', 'short', 'essay')),
  content text not null,
  options jsonb not null default '[]'::jsonb,
  correct text not null,
  explanation text not null default '',
  points numeric(6, 2) not null default 0,
  image_key text not null default '',
  image_url text not null default '',
  geogebra text not null default ''
);

create index if not exists questions_grade_idx on public.questions (grade);
create index if not exists questions_chapter_idx on public.questions (chapter);
create index if not exists questions_level_idx on public.questions (level);
create index if not exists questions_qtype_idx on public.questions (qtype);
create index if not exists questions_grade_chapter_level_qtype_idx
  on public.questions (grade, chapter, level, qtype);

create table if not exists public.theory_notes (
  id bigint primary key,
  grade smallint not null check (grade in (10, 11, 12)),
  chapter text not null,
  title text not null,
  content text not null,
  order_index integer not null default 0,
  source_name text not null default '',
  source_url text not null default '',
  created_at timestamptz
);

create index if not exists theory_notes_grade_idx on public.theory_notes (grade);
create index if not exists theory_notes_chapter_idx on public.theory_notes (chapter);
create index if not exists theory_notes_grade_order_idx on public.theory_notes (grade, order_index);

alter table public.questions enable row level security;
alter table public.theory_notes enable row level security;

grant select on public.questions to anon, authenticated;
grant insert, update, delete on public.questions to authenticated;
grant all on public.questions to service_role;

grant select on public.theory_notes to anon, authenticated;
grant insert, update, delete on public.theory_notes to authenticated;
grant all on public.theory_notes to service_role;

